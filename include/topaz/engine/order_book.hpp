#pragma once

#include <list>
#include <map>
#include <unordered_map>

#include "../types.hpp"
#include "event.hpp"

namespace tpz::eng {

/// @brief Order book with matching engine
class OrderBook {
 public:
  /// @brief Creates an empty order book
  OrderBook() noexcept;

  /// @brief Submits a request to the engine.
  /// A request is a new market order, a new limit order, or a cancel.
  void submit(Request request);

  /// @brief Submits a request to the engine and records events.
  /// A request is a new market order, a new limit order, or a cancel.
  /// @param out A vector to push events generated by the engine into.
  void submit(Request request, std::vector<Event>& out);

  /// @brief Gets a map of order ID -> order
  const std::unordered_map<OrderId, RestingOrder>& orders() const;

 private:
  std::unordered_map<OrderId, RestingOrder> orders_;
  std::map<Price, std::list<OrderId>> sell_orders_;
  std::map<Price, std::list<OrderId>, std::greater<Price>> buy_orders_;

  OrderId next_id_;

  /// Helper to cancel an order. Called by `submit`.
  void cancel(Cancel c, std::vector<Event>* out);

  /// Helper to match an order. Called by `submit`.
  void dispatch(NewLimit order, std::vector<Event>* out);

  /// Helper to match an order. Called by `submit`.
  void dispatch(NewMarket order, std::vector<Event>* out);

  // Helper to generate an ID for a new order. Called by `dispatch`.
  [[nodiscard]] OrderId gen_id();

  /// Helper to match a fill-or-kill order. Called by `dispatch`.
  bool can_fulfill(Side side, Price limit, Qty qty);

  /// Helper to match an order. Called by `dispatch`.
  Qty sweep(OrderId id, Side side, Price limit, Qty qty,
            std::vector<Event>* out);

  /// Helper to rest the remainder of an order. Called by `dispatch`.
  void rest(OrderId id, Side side, Price price, Qty rem);

  /// Helper to emit events. Called by other helpers.
  void emit(std::vector<Event>* out, Event e);
};

}  // namespace tpz::eng
